# Badge class per status value (appointments and billing)
STATUS_BADGES = {
    "pending": "badge-amber",
    "confirmed": "badge-brand",
    "in_queue": "badge-blue",
    "completed": "badge-slate",
    "cancelled": "badge-red",
    "active": "badge-green",
    "past_due": "badge-orange",
}


@register.simple_tag
def icon(name, css="h-5 w-5", stroke="2"):
    paths = ICONS.get(name, ICONS["info"])
    return format_html(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="{}" stroke-linecap="round" stroke-linejoin="round" class="{}" aria-hidden="true">{}</svg>',
        stroke, css, mark_safe(paths),
    )


@register.filter
def status_badge(status):
    return STATUS_BADGES.get(status, "badge-slate")


@register.filter
def days_left(moment):
    """Whole days until a datetime, rounded up (0 once it has passed)."""
    if not moment:
        return 0
    seconds = (moment - timezone.now()).total_seconds()
    return max(0, math.ceil(seconds / 86400))


@register.filter
def initials(name):
    parts = str(name or "").split()
    if not parts:
        return "?"
    letters = parts[0][0] + (parts[-1][0] if len(parts) > 1 else "")
    return letters.upper()
